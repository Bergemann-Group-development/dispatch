!> =============================================================================
!> =============================================================================
MODULE slope
  implicit none
CONTAINS

!> =============================================================================
!> =============================================================================
SUBROUTINE moncen1 (f, g)
  real, intent(in)  :: f(:,:,:)
  real, intent(out) :: g(:,:,:,:)
  real, allocatable :: ls(:,:,:), cs(:,:,:)
  integer:: i, j, k, m(3)
  !-----------------------------------------------------------------------------
  m = shape(f)
  !-----------------------------------------------------------------------------
  ! x-direction
  !-----------------------------------------------------------------------------
  allocate (ls(m(1),m(2),m(3)))
  allocate (cs(m(1),m(2),m(3)))
  do k=1,m(3)
    do j=1,m(2)
      do i=2,m(1)
        ls(i,j,k)   = f(i,j,k)-f(i-1,j,k)
      end do
    end do
  end do
  !
  do k=1,m(3)
    do j=1,m(2)
      do i=2,m(1)-1
        cs(i,j,k) = ls(i,j,k)*ls(i-1,j,k)/(ls(i,j,k)+ls(i-1,j,k))
      end do
    end do
  end do
  !
  do k=1,m(3)
    do j=1,m(2)
      do i=2,m(1)-1
        g(i,j,k,1) = cs(i,j,k)*(1.0+sign(1.0,ls(i,j,k)*ls(i-1,j,k)))
      end do
    end do
  end do
  g(1   ,:,:,1) = 0.0
  g(m(1),:,:,1) = 0.0
  !-----------------------------------------------------------------------------
  ! y-direction
  !-----------------------------------------------------------------------------
  do k=1,m(3)
    do j=2,m(2)
      do i=1,m(1)
        ls(i,j,k)   = f(i,j,k)-f(i,j-1,k)
      end do
    end do
  end do
  !
  do k=1,m(3)
    do j=1,m(2)
      do i=2,m(1)-1
        cs(i,j,k) = ls(i,j,k)*ls(i,j-1,k)/(ls(i,j,k)+ls(i,j-1,k))
      end do
    end do
  end do
  !
  do k=1,m(3)
    do j=1,m(2)
      do i=2,m(1)-1
        g(i,j,k,2) = cs(i,j,k)*(1.0+sign(1.0,ls(i,j,k)*ls(i,j-1,k)))
      end do
    end do
  end do
  g(:,1   ,:,2) = 0.0
  g(:,m(2),:,2) = 0.0
  !-----------------------------------------------------------------------------
  ! z-direction
  !-----------------------------------------------------------------------------
  do k=1,m(3)
    do j=2,m(2)
      do i=1,m(1)
        ls(i,j,k)   = f(i,j,k)-f(i,j,k-1)
      end do
    end do
  end do
  !
  do k=2,m(3)-1
    do j=1,m(2)
      do i=1,m(1)
        cs(i,j,k) = ls(i,j,k)*ls(i,j,k-1)/(ls(i,j,k)+ls(i,j,k-1))
      end do
    end do
  end do
  !
  do k=2,m(3)-1
    do j=1,m(2)
      do i=1,m(1)
        g(i,j,k,3) = cs(i,j,k)*(1.0+sign(1.0,ls(i,j,k)*ls(i,j-1,k)))
      end do
    end do
  end do
  g(:,:,1   ,3) = 0.0
  g(:,:,m(3),3) = 0.0
END SUBROUTINE moncen1

!> =============================================================================
!> =============================================================================
SUBROUTINE moncen2 (f, g)
  real, intent(in)  :: f(:,:,:)
  real, intent(out) :: g(:,:,:,:)
  real, allocatable :: l(:,:,:)
  real, allocatable :: c(:,:,:)
  integer:: i, j, k, m(3)
  !-----------------------------------------------------------------------------
  m = shape(f)
  !-----------------------------------------------------------------------------
  ! x-direction
  !-----------------------------------------------------------------------------
  allocate (l(m(1),m(2),m(3)))
  allocate (c(m(1),m(2),m(3)))
  l(2:m(1)  ,:,:)   = f(2:m(1)  ,:,:) - f(1:m(1)-1,:,:)
  c(2:m(1)-1,:,:)   = l(2:m(1)-1,:,:) * l(1:m(1)-2,:,:)/(l(1:m(1)-2,:,:)+l(2:m(1)-1,:,:))
  g(2:m(1)-1,:,:,1) = g(2:m(1)-1,:,:,1)*(1.0 + sign(1.0, l(1:m(1)-2,:,:)*l(2:m(1)-1,:,:)))
  g(1   ,:,:,1) = 0.0
  g(m(1),:,:,1) = 0.0
  !-----------------------------------------------------------------------------
  ! y-direction
  !-----------------------------------------------------------------------------
  l(:,2:m(2)  ,:)   = f(:,2:m(2)  ,:) - f(:,1:m(1)-1,:)
  c(:,2:m(2)-1,:)   = l(:,2:m(2)-1,:) * l(:,1:m(1)-2,:)/(l(:,1:m(2)-2,:)+l(:,2:m(2)-1,:))
  g(:,2:m(2)-1,:,2) = g(:,2:m(2)-1,:,2)*(1.0 + sign(1.0, l(:,1:m(2)-2,:)*l(:,2:m(2)-1,:)))
  g(:,1   ,:,2) = 0.0
  g(:,m(2),:,2) = 0.0
  !-----------------------------------------------------------------------------
  ! z-direction
  !-----------------------------------------------------------------------------
  l(:,:,2:m(3)  )   = f(:,:,2:m(3)  ) - f(:,:,1:m(3)-1)
  c(:,:,2:m(3)-1)   = l(:,:,2:m(3)-1) * l(:,:,1:m(3)-2)/(l(:,:,1:m(3)-2)+l(:,:,2:m(3)-1))
  g(:,:,2:m(3)-1,3) = g(:,:,2:m(3)-1,3)*(1.0 + sign(1.0, l(:,:,1:m(3)-2)*l(:,:,2:m(3)-1)))
  g(:,:,1   ,3) = 0.0
  g(:,:,m(3),3) = 0.0
END SUBROUTINE moncen2
END MODULE slope

!> =============================================================================
!> =============================================================================
PROGRAM test
  USE omp_lib
  USE slope
  implicit none
  integer:: n, nit
  procedure(moncen1), pointer:: moncen
  !-----------------------------------------------------------------------------
  read (*,*) n, nit
  moncen => moncen1
  call cost
  moncen => moncen2
  call cost
contains
  subroutine cost
    integer:: it
    real, allocatable :: fa(:,:,:), ga(:,:,:,:)
    real, pointer     :: fp(:,:,:), gp(:,:,:,:)
    real(8):: start, total
    !---------------------------------------------------------------------------
    total = 0d0
    do it=1,nit
      allocate (fa(n,n,n), ga(n,n,n,3))
      fa = 1.0
      start = omp_get_wtime()
      call moncen (fa, ga)
      total = total + (omp_get_wtime() - start)
      deallocate (fa, ga)
    end do
    print '(2i5,f6.1," ns/cell")', n, nit, total*1e9/n**3/nit
  end subroutinE cost
END PROGRAM test
